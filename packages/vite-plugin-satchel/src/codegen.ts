import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, isAbsolute, join, relative, sep } from 'node:path';
import type { Manifest } from './manifest';

export interface Inventory {
  pages: string[];
  excludedFiles: string[];
  excludedDirectories: string[];
}

const slash = (path: string): string => path.replaceAll('\\', '/');
const safePage = (page: string): boolean => /^[A-Za-z0-9_-]+(?:\/[A-Za-z0-9_-]+)*$/.test(page);
const within = (root: string, path: string): boolean => {
  const from = relative(root, path);
  return from === '' || (!from.startsWith(`..${sep}`) && from !== '..' && !isAbsolute(from));
};

/** Match PHP inventory: no directory symlinks, no traversal, no escaped file symlinks. */
export function inventory(root: string, extensions: readonly string[]): Inventory {
  const result: Inventory = { pages: [], excludedFiles: [], excludedDirectories: [] };
  if (!existsSync(root)) return result;
  const canonicalRoot = realpathSync(root);
  const pages = new Set<string>();
  const walk = (directory: string) => {
    for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
      const path = join(directory, entry.name);
      const fromRoot = slash(relative(canonicalRoot, path));
      if (entry.isDirectory()) {
        if (!safePage(fromRoot)) result.excludedDirectories.push(fromRoot);
        else walk(path);
        continue;
      }
      if (entry.isSymbolicLink() && (!existsSync(path) || statSync(path).isDirectory())) {
        result.excludedDirectories.push(fromRoot);
        continue;
      }
      const extension = extname(path).slice(1);
      if (!extensions.includes(extension)) continue;
      if (!within(canonicalRoot, realpathSync(path))) {
        throw new Error(`[Satchel] Page symlink [${path}] escapes its registered page directory.`);
      }
      const page = fromRoot.slice(0, -extension.length - 1);
      if (safePage(page)) pages.add(page);
      else result.excludedFiles.push(fromRoot);
    }
  };
  walk(canonicalRoot);
  result.pages = [...pages].sort();
  return result;
}

export interface Snapshot {
  manifest: Manifest;
  overrides: Inventory;
  vendors: Inventory[];
  pageNames: string[];
}

export function snapshot(manifest: Manifest): Snapshot {
  const overrides = inventory(manifest.override_path, [...new Set(manifest.namespaces.flatMap((entry) => entry.extensions))]);
  const vendors = manifest.namespaces.map((entry) => inventory(entry.path, entry.extensions));
  const names = new Set<string>();
  manifest.namespaces.forEach((entry, index) => {
    for (const page of vendors[index]!.pages) names.add(`${entry.namespace}::${page}`);
    for (const page of overrides.pages) {
      if (page.startsWith(`${entry.namespace}/`) && entry.extensions.some((extension) => {
        const path = join(manifest.override_path, `${page}.${extension}`);
        return existsSync(path) && statSync(path).isFile();
      })) names.add(`${entry.namespace}::${page.slice(entry.namespace.length + 1)}`);
    }
  });
  return { manifest, overrides, vendors, pageNames: [...names].sort() };
}

function keyPrefix(importerDirectory: string, directory: string): string {
  const path = slash(relative(importerDirectory, directory));
  return path.startsWith('.') ? path : `./${path}`;
}

// Escape only path literals; append glob operators afterwards. JSON.stringify
// supplies JS string escaping independently of glob escaping.
const escapeGlob = (path: string): string => path.replace(/[!*?{}()[\]]/g, '\\$&');

function glob(prefix: string, extensions: readonly string[], files: Inventory, eager: boolean, positivePatterns?: string[]): string {
  if (extensions.length === 0) return '{}';
  const patterns = [
    ...(positivePatterns ?? extensions.map((extension) => `${escapeGlob(prefix)}/**/*.${extension}`)),
    ...files.excludedDirectories.map((directory) => `!${escapeGlob(`${prefix}/${directory}`)}/**`),
    ...files.excludedFiles.map((file) => `!${escapeGlob(`${prefix}/${file}`)}`),
  ];
  return `import.meta.glob(${JSON.stringify(patterns)}, { eager: ${eager}, exhaustive: true })`;
}

/** Literal calls let Vite own code splitting, framework transforms, and HMR. */
export function generateModule(data: Snapshot, importerDirectory: string, eager: boolean): string {
  const { manifest } = data;
  const overridePrefix = keyPrefix(importerDirectory, manifest.override_path);
  const extensions = [...new Set(manifest.namespaces.flatMap((entry) => entry.extensions))];
  const lines = [
    '// Generated by vite-plugin-satchel. Component identity remains namespace::Page.',
    `const overrides = ${glob(overridePrefix, extensions, data.overrides, eager, manifest.namespaces.flatMap((entry) =>
      entry.extensions.map((extension) => `${escapeGlob(`${overridePrefix}/${entry.namespace}`)}/**/*.${extension}`),
    ))};`,
  ];
  manifest.namespaces.forEach((entry, index) => {
    lines.push(`const namespace${index} = ${glob(keyPrefix(importerDirectory, entry.path), entry.extensions, data.vendors[index]!, eager)};`);
  });
  lines.push('export default {', `  overridePath: ${JSON.stringify(overridePrefix)},`, '  overrides,', '  namespaces: [');
  manifest.namespaces.forEach((entry, index) => {
    lines.push(`    { namespace: ${JSON.stringify(entry.namespace)}, path: ${JSON.stringify(keyPrefix(importerDirectory, entry.path))}, extensions: ${JSON.stringify(entry.extensions)}, pages: namespace${index} },`);
  });
  lines.push('  ],', '};', '');
  return lines.join('\n');
}

export function generateDeclarations(names: readonly string[]): string {
  return '// Generated by vite-plugin-satchel. Do not edit.\nexport type SatchelPage ='
    + (names.length ? `\n${names.map((name) => `  | ${JSON.stringify(name)}`).join('\n')}` : ' never') + ';\n';
}

export function writeDeclarations(path: string, names: readonly string[]): void {
  const content = generateDeclarations(names);
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}
